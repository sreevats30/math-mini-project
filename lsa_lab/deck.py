"""Build the presentation (python-pptx) from the same pipeline as the app.

    python main.py deck      ->  presentation/MFDS_LSA_Presentation.pptx

Every number on a slide is read from the analysis results, and every chart is a
figure generated by lsa_lab.figures, so the deck cannot drift out of date.
Equations are typeset with matplotlib's mathtext and inserted as images.
Speaker notes on each slide carry the explanation to say out loud.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402
from pptx import Presentation  # noqa: E402
from pptx.dml.color import RGBColor  # noqa: E402
from pptx.enum.shapes import MSO_SHAPE  # noqa: E402
from pptx.enum.text import MSO_ANCHOR, PP_ALIGN  # noqa: E402
from pptx.oxml.ns import qn  # noqa: E402
from pptx.util import Emu, Inches, Pt  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "presentation" / "MFDS_LSA_Presentation.pptx"
EQ_DIR = ROOT / "presentation" / "equations"

# Edit this list if you wish to display author names on the title slide (currently empty for anonymity).
AUTHORS: list[str] = []
COURSE = "Mathematical Foundations of Data Science: mini-project"

W, H = 13.333, 7.5
M = 0.6                      # outer margin
HEAD, BODY = "Cambria", "Calibri"
INK, INK_SOFT, MUTED, RULE = "18202B", "4D5766", "7A8494", "D5DCE3"
TINT, WHITE, DARK = "EEF2F5", "FFFFFF", "143038"
U_C, S_C, V_C, A_C = "0F7A80", "B07A10", "6A4FC4", "2B4C7E"
HIGHLIGHT = "F7EFDD"

STEPS = [("Words", A_C), ("SVD", U_C), ("Keep k", S_C), ("Cluster", V_C), ("Search", U_C)]


def rgb(h: str) -> RGBColor:
    return RGBColor.from_string(h)


# ============================================================================ primitives
class Deck:
    def __init__(self):
        self.prs = Presentation()
        self.prs.slide_width = Inches(W)
        self.prs.slide_height = Inches(H)
        self.blank = self.prs.slide_layouts[6]
        self.n = 0
        EQ_DIR.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------- slides
    def slide(self, dark: bool = False, step: int | None = None, number: bool = True):
        s = self.prs.slides.add_slide(self.blank)
        self.n += 1
        bg = s.background.fill
        bg.solid()
        bg.fore_color.rgb = rgb(DARK if dark else WHITE)
        if number and not dark:
            self.text(s, W - M - 1.0, H - 0.5, 1.0, 0.3, str(self.n), size=11, color=MUTED, align=PP_ALIGN.RIGHT)
        if step is not None:
            self.tracker(s, step)
        return s

    def tracker(self, s, step: int):
        """Small row of squares in the footer: where this slide sits in the 5-step pipeline."""
        x, y, sz, gap = M, H - 0.46, 0.15, 0.07
        for i, (name, color) in enumerate(STEPS):
            r = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x + i * (sz + gap)), Inches(y), Inches(sz), Inches(sz))
            r.fill.solid()
            r.fill.fore_color.rgb = rgb(color if i == step else RULE)
            r.line.fill.background()
            r.shadow.inherit = False
        label = f"Step {step + 1} of 5: {STEPS[step][0]}"
        self.text(s, x + 5 * (sz + gap) + 0.12, y - 0.07, 3.0, 0.3, label, size=11, color=MUTED)

    def title(self, s, text: str, dark: bool = False, size: int = 30, y: float = 0.45, h: float = 1.15):
        self.text(s, M, y, W - 2 * M, h, text, size=size, color=WHITE if dark else INK, font=HEAD, bold=True,
                  anchor=MSO_ANCHOR.TOP, line_spacing=1.0)

    def notes(self, s, text: str):
        s.notes_slide.notes_text_frame.text = text.strip()

    # ------------------------------------------------------------- text
    def text(self, s, x, y, w, h, content, size=16, color=INK, font=BODY, bold=False, italic=False,
             align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, line_spacing=1.12, space_after=6, bullets=False,
             name: str | None = None):
        """content: a string, or a list of paragraphs; each paragraph a string or a list of
        (text, {"bold":…, "color":…, "italic":…, "size":…, "font":…}) runs."""
        tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
        if name:
            tb.name = name
        tf = tb.text_frame
        tf.word_wrap = True
        tf.vertical_anchor = anchor
        tf.margin_left = tf.margin_right = Inches(0.02)
        tf.margin_top = tf.margin_bottom = Inches(0.02)
        paras = [content] if isinstance(content, str) else content
        for i, para in enumerate(paras):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.alignment = align
            p.line_spacing = line_spacing
            p.space_after = Pt(space_after)
            runs = [(para, {})] if isinstance(para, str) else para
            for t, opt in runs:
                r = p.add_run()
                r.text = t
                f = r.font
                f.name = opt.get("font", font)
                f.size = Pt(opt.get("size", size))
                f.bold = opt.get("bold", bold)
                f.italic = opt.get("italic", italic)
                f.color.rgb = rgb(opt.get("color", color))
            if bullets:
                pPr = p._p.get_or_add_pPr()
                pPr.set("marL", str(Emu(Inches(0.28))))
                pPr.set("indent", str(-Emu(Inches(0.22))))
                bu = pPr.makeelement(qn("a:buChar"), {"char": "•"})
                for old in pPr.findall(qn("a:buNone")):
                    pPr.remove(old)
                pPr.append(bu)
        return tb

    def rect(self, s, x, y, w, h, fill=TINT, line: str | None = None, rounded=False, name=None):
        shp = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE if rounded else MSO_SHAPE.RECTANGLE,
                                 Inches(x), Inches(y), Inches(w), Inches(h))
        if rounded:
            shp.adjustments[0] = 0.08
        shp.fill.solid()
        shp.fill.fore_color.rgb = rgb(fill)
        if line:
            shp.line.color.rgb = rgb(line)
            shp.line.width = Pt(1)
        else:
            shp.line.fill.background()
        shp.shadow.inherit = False
        for ref in shp._element.iter(qn("a:effectRef")):
            ref.set("idx", "0")
        if name:
            shp.name = name
        return shp

    def block(self, s, x, y, w, h, color, base: str, sup: str | None = None, size=26):
        """A coloured matrix block with its name, e.g. V with a superscript T."""
        r = self.rect(s, x, y, w, h, fill=color)
        tf = r.text_frame
        tf.margin_left = tf.margin_right = 0
        p = tf.paragraphs[0]
        p.alignment = PP_ALIGN.CENTER
        for t, is_sup in [(base, False), (sup, True)]:
            if not t:
                continue
            run = p.add_run()
            run.text = t
            run.font.size = Pt(size)
            run.font.name = HEAD
            run.font.bold = True
            run.font.color.rgb = rgb(WHITE)
            if is_sup:
                run.font._rPr.set("baseline", "30000")
        tf.vertical_anchor = MSO_ANCHOR.MIDDLE
        return r

    def image(self, s, path, x, y, w=None, h=None, align="left"):
        """Insert an image inside the box (x, y, w, h), keeping its aspect ratio."""
        iw, ih = Image.open(path).size
        ar = iw / ih
        if w and h:
            if w / h > ar:
                ww, hh = h * ar, h
            else:
                ww, hh = w, w / ar
        elif w:
            ww, hh = w, w / ar
        else:
            ww, hh = h * ar, h
        xx = x if align == "left" else x + ((w or ww) - ww) / 2 if align == "center" else x + (w or ww) - ww
        return s.shapes.add_picture(str(path), Inches(xx), Inches(y), Inches(ww), Inches(hh))

    def eq(self, s, latex: str, x, y, size=24, color=INK, max_w=None, align="left"):
        """Typeset an equation with mathtext and place it at its natural size (size in pt)."""
        key = hashlib.sha1(f"{latex}|{size}|{color}".encode()).hexdigest()[:12]
        path = EQ_DIR / f"eq_{key}.png"
        if not path.exists():
            plt.rcParams["mathtext.fontset"] = "cm"
            fig = plt.figure(figsize=(0.01, 0.01))
            fig.text(0, 0, f"${latex}$", fontsize=size, color=f"#{color}")
            fig.savefig(path, dpi=300, transparent=True, bbox_inches="tight", pad_inches=0.03)
            plt.close(fig)
        iw, ih = Image.open(path).size
        w_in, h_in = iw / 300, ih / 300
        if max_w and w_in > max_w:
            h_in *= max_w / w_in
            w_in = max_w
        xx = x if align == "left" else x - w_in / 2 if align == "center" else x - w_in
        s.shapes.add_picture(str(path), Inches(xx), Inches(y), Inches(w_in), Inches(h_in))
        return w_in, h_in

    def stat(self, s, x, y, w, value, label, color=INK, size=40, label_size=14):
        self.text(s, x, y, w, 0.8, value, size=size, color=color, font=HEAD, bold=True, space_after=0,
                  line_spacing=1.0)
        self.text(s, x, y + size / 72 * 1.18, w, 0.9, label, size=label_size, color=INK_SOFT, space_after=0)

    def save(self, path: Path = OUT) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        self.prs.save(str(path))
        return path


# ============================================================================ the deck
def build(out: dict, figs: dict) -> Path:
    R = out["results"]["corpora"]
    exps = out["experiments"]
    news, classic, science = R["news"], R["classic"], R["science"]
    nex = exps["news"]
    F = {k: Path(v) for k, v in figs["paths"].items()}
    APP = ROOT / "figures" / "app"
    k = news["k"]
    ari_raw = news["clustering"]["raw"]["ARI"]["mean"]
    ari_lsa = news["clustering"]["lsa"]["ARI"]["mean"]
    nmi_raw = news["clustering"]["raw"]["NMI"]["mean"]
    nmi_lsa = news["clustering"]["lsa"]["NMI"]["mean"]
    ratio = ari_lsa / ari_raw
    ey = news["eckart_young"]

    d = Deck()

    # ------------------------------------------------------------------ 1 title
    s = d.slide(dark=True, number=False)
    d.text(s, M, 0.9, 8.0, 0.4, COURSE, size=16, color="9FC7C9")
    d.text(s, M, 1.4, 8.4, 2.0, "Clustering ideas, not words", size=54, color=WHITE, font=HEAD, bold=True,
           line_spacing=0.95)
    d.text(s, M, 3.35, 7.6, 1.2, "Finding topics in documents with Latent Semantic Analysis and the "
           "singular value decomposition", size=22, color="D9E6E8", line_spacing=1.1)
    if AUTHORS:
        d.text(s, M, 5.75, 8.0, 0.9, [" and ".join(AUTHORS)], size=18, color=WHITE)
    # the factorisation drawn as coloured blocks, roughly to scale
    bx, by, tall, small = 8.35, 1.3, 3.0, 0.55
    x = bx
    d.block(s, x, by, 1.15, tall, A_C, "A"); x += 1.15
    d.text(s, x, by + tall / 2 - 0.35, 0.45, 0.6, "=", size=30, color="9FC7C9", font=HEAD, align=PP_ALIGN.CENTER)
    x += 0.45
    d.block(s, x, by, small, tall, U_C, "U"); x += small
    for label, col, w_, sup in [("Σ", S_C, small, None), ("V", V_C, 1.15, "T")]:
        d.text(s, x, by + small / 2 - 0.33, 0.3, 0.5, "·", size=30, color="9FC7C9", font=HEAD,
               align=PP_ALIGN.CENTER)
        x += 0.3
        d.block(s, x, by, w_, small, col, label, sup)
        x += w_
    d.text(s, bx, by + tall + 0.2, 4.3, 0.8, f"{news['terms']:,} words × {news['documents']} articles, kept as {k} concepts",
           size=14, color="9FC7C9")
    d.notes(s, f"""
Our project asks a simple question: can a computer group documents by what they are about, rather than by the exact words they use?
The answer is Latent Semantic Analysis. It is one idea from linear algebra: write the documents as a matrix A and take its singular value decomposition, A = U Σ Vᵀ.
The coloured blocks on the right are that factorisation for our real data set: {news['terms']:,} words by {news['documents']} news articles, compressed to {k} concepts.
""")

    # ------------------------------------------------------------------ 2 the problem
    s = d.slide(step=None)
    a_t, b_t = news["showcase_pair"]["a"], news["showcase_pair"]["b"]
    titles = list(nex.corpus.titles)
    ia, ib = titles.index(a_t), titles.index(b_t)
    d.title(s, "Two articles about web search share no words, so word vectors call them unrelated")
    for i_, (x0, j) in enumerate([(M, ia), (M + 6.15, ib)]):
        d.rect(s, x0, 1.85, 5.95, 2.55, fill=TINT, rounded=True)
        body = nex.corpus.texts[j]
        body = body[len(nex.corpus.titles[j]) + 2:] if body.startswith(nex.corpus.titles[j]) else body
        if len(body) > 230:
            body = body[:227].rsplit(" ", 1)[0] + " …"
        kept = sorted(set(nex.tdm.tokens(nex.corpus.texts[j])))
        d.text(s, x0 + 0.3, 2.0, 5.4, 2.4, [
            [(nex.corpus.titles[j], {"bold": True, "size": 17, "font": HEAD})],
            [(body, {"size": 14, "color": INK_SOFT})],
            [("kept words: ", {"size": 12, "color": MUTED}), (", ".join(kept[:14]), {"size": 12, "color": U_C})],
        ], space_after=8)
    d.stat(s, M, 4.75, 3.8, "0", "indexed words in common", color=INK)
    d.stat(s, M + 4.1, 4.75, 3.8, f"{news['showcase_pair']['raw_cosine']:.2f}",
           "cosine similarity of their word vectors", color=INK)
    d.stat(s, M + 8.2, 4.75, 3.9, f"{news['showcase_pair']['lsa_cosine']:.2f}",
           f"cosine similarity after keeping {k} concepts", color=U_C)
    d.text(s, M, 6.25, 12.0, 0.6, "Both are filed under Sci/Tech in the AG News collection. The rest of this talk "
           "explains where the 0.98 comes from.", size=14, color=INK_SOFT)
    d.notes(s, f"""
Here are two real articles from our data. One is about desktop search tools, the other about a new version of Google Groups. A human sees immediately that they are both about internet search products.
After removing common words, the two articles have no word in common. Represented as word vectors, they are perpendicular: cosine similarity exactly 0. Any method that compares words directly, including k-means on TF-IDF vectors, treats them as unrelated.
After LSA keeps {k} concepts, their cosine similarity is {news['showcase_pair']['lsa_cosine']:.2f}. The other 398 articles connect their vocabularies: words like Google, search and software keep appearing together, and the SVD turns that into shared concepts.
""")

    # ------------------------------------------------------------------ 3 pipeline
    s = d.slide()
    d.title(s, "Five steps from raw text to topics")
    steps = [
        ("Count words", "Clean each document and count its meaningful words.", r"c_{ij}=\mathrm{count}(w_i,d_j)", A_C),
        ("Build A", "Stack the counts as columns and weight with TF-IDF.", r"A\in\mathbb{R}^{m\times n}", A_C),
        ("Factorise", "Take the singular value decomposition of A.", r"A=U\Sigma V^{\top}", U_C),
        ("Keep k", "Keep only the k strongest concepts.", r"A_k=U_k\Sigma_kV_k^{\top}", S_C),
        ("Use it", "Cluster documents, and fold in queries to search.", r"\hat q=\Sigma_k^{-1}U_k^{\top}q", V_C),
    ]
    bw, gap, y0 = 2.22, 0.25, 2.0
    for i, (head, desc, eq_, col) in enumerate(steps):
        x0 = M + i * (bw + gap)
        d.rect(s, x0, y0, bw, 3.55, fill=TINT, rounded=True)
        d.text(s, x0 + 0.22, y0 + 0.2, 1.0, 0.6, str(i + 1), size=30, color=col, font=HEAD, bold=True)
        d.text(s, x0 + 0.22, y0 + 0.85, bw - 0.4, 0.5, head, size=19, color=INK, font=HEAD, bold=True)
        d.text(s, x0 + 0.22, y0 + 1.35, bw - 0.42, 1.2, desc, size=14, color=INK_SOFT)
        d.eq(s, eq_, x0 + 0.22, y0 + 2.8, size=15, color=col, max_w=bw - 0.4)
        if i < len(steps) - 1:
            d.text(s, x0 + bw - 0.02, y0 + 1.35, gap + 0.04, 0.5, "›", size=26, color=MUTED, align=PP_ALIGN.CENTER)
    d.text(s, M, 5.95, 12.0, 0.9, "Each step is one chapter of the interactive lab, and is checked by the test suite.",
           size=15, color=INK_SOFT)
    d.notes(s, """
The whole method is five steps. Steps 1 and 2 turn text into a matrix. Step 3 is the singular value decomposition. Step 4 keeps only the strongest k concepts; this truncation is where LSA gets its power. Step 5 uses the compressed representation: k-means clustering, and search by folding a new query into the same concept space.
The rest of the talk follows these five steps, and the small squares at the bottom of each slide show which step we are on.
""")

    # ------------------------------------------------------------------ 4 data
    s = d.slide()
    d.title(s, "Three collections, each chosen to teach one thing")
    rows = [
        ("Collection", "Matrix A", "Why it is here"),
        ("Classic: 9 paper titles from the 1990 LSA paper", f"{classic['terms']} × {classic['documents']}",
         "Small enough to read every number. Reproduces the paper's published results exactly."),
        ("Science: 24 one-sentence blurbs (our first version)", f"{science['terms']} × {science['documents']}",
         "Shows when LSA has little to work with: almost no shared vocabulary."),
        ("News: 400 real AG News articles, 100 per section", f"{news['terms']:,} × {news['documents']}",
         "Real, messy text. The main benchmark for clustering and search."),
    ]
    tbl = s.shapes.add_table(len(rows), 3, Inches(M), Inches(1.95), Inches(W - 2 * M), Inches(3.6)).table
    widths = [4.7, 1.7, W - 2 * M - 6.4]
    for ci, wv in enumerate(widths):
        tbl.columns[ci].width = Inches(wv)
    for ri, row in enumerate(rows):
        tbl.rows[ri].height = Inches(0.62 if ri == 0 else 0.95)
        for ci, val in enumerate(row):
            cell = tbl.cell(ri, ci)
            cell.fill.solid()
            cell.fill.fore_color.rgb = rgb(INK if ri == 0 else (TINT if ri % 2 == 0 else WHITE))
            cell.margin_left = cell.margin_right = Inches(0.15)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            tf = cell.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            r = p.add_run()
            r.text = val
            r.font.name = BODY
            r.font.size = Pt(15 if ri else 14)
            r.font.bold = ri == 0 or ci == 1
            r.font.color.rgb = rgb(WHITE if ri == 0 else INK)
    d.text(s, M, 5.95, 12.0, 0.8, "Every number in this deck is produced by one command, python main.py deck, "
           "and checked by the tests in tests/test_lsa.py.", size=14, color=INK_SOFT)
    d.notes(s, f"""
We use three collections. The classic one is the worked example from Deerwester and colleagues' 1990 paper that introduced LSA: nine titles, twelve words. It is small enough to see every number, and our code reproduces the paper's published numbers exactly.
The science collection is the one we started with: 24 one-sentence blurbs. It taught us something: when documents share almost no words, the SVD has nothing to find.
The news collection is the main experiment: 400 real articles from the AG News corpus, 100 each from World, Sports, Business and Sci/Tech. The labels are only used to score the result, never to build it.
""")

    # ------------------------------------------------------------------ 5 matrix A
    s = d.slide(step=0)
    d.title(s, "Documents become columns of a sparse term–document matrix A")
    d.image(s, F["classic_matrix"], M, 1.75, w=5.4, h=4.95)
    xr = M + 6.0
    d.text(s, xr, 1.85, 6.1, 0.4, "Each entry is the weight of word i in document j:", size=16, color=INK)
    d.eq(s, r"A_{ij}=\frac{w_{ij}}{\|w_{\cdot j}\|_2},\qquad w_{ij}=(1+\ln c_{ij})\left(\ln\frac{1+n}{1+\mathrm{df}_i}+1\right)",
         xr, 2.35, size=17, max_w=6.1)
    d.text(s, xr, 3.45, 6.1, 1.6, [
        "Frequent in this document: larger tf.",
        "Rare in the collection: larger idf.",
        "Every column scaled to length 1, so long and short articles are comparable.",
    ], size=15, color=INK_SOFT, bullets=True, space_after=4)
    d.stat(s, xr, 5.0, 2.9, f"{100 * news['sparsity']:.1f}%", f"of the {news['terms']:,} × {news['documents']} news "
           "matrix is zero", color=A_C)
    ov = (nex.tdm.counts > 0).astype(int)
    shared_ = ov.T @ ov
    yv = np.array(nex.corpus.labels)
    iu = np.triu_indices(len(yv), 1)
    same = (yv[:, None] == yv[None, :])[iu]
    zero_same = float(np.mean(shared_[iu][same] == 0))
    d.stat(s, xr + 3.2, 5.0, 2.9, f"{100 * zero_same:.0f}%", "of same-section article pairs share no word at all",
           color=A_C)
    d.notes(s, f"""
On the left is the full term–document matrix of the classic example: twelve words by nine titles, raw counts. Five titles are about human–computer interaction, four about graph theory.
For real text we weight the counts with TF-IDF: a word counts more when it is frequent in this document and rare across the collection. Then every column is scaled to unit length. Our implementation is written out by hand and a test checks it matches scikit-learn exactly.
The key fact is sparsity: {100 * news['sparsity']:.0f}% of the news matrix is zero, and {100 * zero_same:.0f}% of pairs of articles from the same section have no word in common. Comparing columns of A directly cannot work.
""")

    # ------------------------------------------------------------------ 6 SVD
    s = d.slide(step=1)
    d.title(s, "The SVD splits A into word concepts, strengths and document concepts")
    y0, x0 = 1.95, M + 0.1
    parts = [("A", None, A_C, 1.7, 2.3, f"{news['terms']:,} × {news['documents']}"), ("=", None, None, 0.55, 0, ""),
             ("U", None, U_C, 0.95, 2.3, f"{news['terms']:,} × r"), ("·", None, None, 0.4, 0, ""),
             ("Σ", None, S_C, 0.95, 0.95, "r × r"), ("·", None, None, 0.4, 0, ""),
             ("V", "T", V_C, 1.7, 0.95, f"r × {news['documents']}")]
    x = x0
    for label, sup, col, w_, h_, dim in parts:
        if col is None:
            yy = y0 + 0.85 if label == "=" else y0 + 0.2
            d.text(s, x, yy, w_, 0.6, label, size=30, color=MUTED, font=HEAD, align=PP_ALIGN.CENTER)
        else:
            d.block(s, x, y0, w_, h_, col, label, sup)
            d.text(s, x - 0.2, y0 + h_ + 0.08, w_ + 0.4, 0.35, dim, size=12, color=INK_SOFT, align=PP_ALIGN.CENTER)
        x += w_
    xr = 7.9
    d.text(s, xr, 1.9, W - M - xr, 3.2, [
        [("U: ", {"bold": True, "color": U_C}), ("each column is a concept written as word weights. "
                                                "Orthonormal: UᵀU = I.", {})],
        [("Σ: ", {"bold": True, "color": S_C}), ("singular values σ₁ ≥ σ₂ ≥ … ≥ 0, how much of A each "
                                                "concept explains.", {})],
        [("V: ", {"bold": True, "color": V_C}), ("row j says how strongly document j uses each concept. "
                                                "Orthonormal: VᵀV = I.", {})],
    ], size=16, space_after=12)
    d.text(s, M, 4.95, 6.0, 0.4, "Why these are the right directions:", size=16, color=INK)
    d.eq(s, r"A^{\top}A=V\Sigma U^{\top}U\Sigma V^{\top}=V\Sigma^{2}V^{\top}\ \Rightarrow\ A^{\top}Av_i=\sigma_i^{2}v_i",
         M, 5.45, size=19, max_w=7.2)
    d.text(s, xr, 4.95, W - M - xr, 1.8, "V holds the eigenvectors of the document–document matrix AᵀA and U those "
           "of the word–word matrix AAᵀ. Verified numerically to about 10⁻¹⁴ in the app.",
           size=14, color=INK_SOFT)
    d.notes(s, """
The singular value decomposition writes any real matrix as U Σ Vᵀ. Unlike an eigendecomposition it works for rectangular matrices, which is exactly what a words-by-documents matrix is.
U's columns are concepts expressed as word weights. Σ is diagonal and holds the singular values in decreasing order: the strength of each concept. V's rows place each document on the concepts.
Why are these meaningful? Multiply out AᵀA and the U's cancel because UᵀU is the identity: AᵀA = V Σ² Vᵀ. So V contains the eigenvectors of the document similarity matrix and σᵢ² its eigenvalues. Likewise U for the word co-occurrence matrix AAᵀ. In the app we check each of these properties numerically on the real matrix.
""")

